import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { renderWithProviders } from '@/test/renderWithProviders';
import { tokenStorage } from '@/api/session';
import { carritoApi } from '@/features/carrito/api/carritoApi';
import { pagosApi } from '@/features/pagos/api/pagosApi';
import { CheckoutPage } from '@/pages/CheckoutPage';
import { crearCarrito, crearItem, respuestaMe } from '@/features/carrito/pantalla-test-utils';
import { reservasApi } from '@/features/reservas/api/reservasApi';
vi.mock('@/features/pagos/utils/stripe', () => ({ getStripe: () => Promise.resolve({}) }));
beforeEach(() => {
  sessionStorage.clear(); tokenStorage.set('test-token');
  global.fetch = vi.fn().mockResolvedValue(respuestaMe(3));
  vi.spyOn(carritoApi, 'getCurrent').mockResolvedValue(crearCarrito());
  vi.spyOn(carritoApi, 'getItems').mockResolvedValue({ items: [crearItem()], total: 601 });
  vi.spyOn(pagosApi, 'getResumen').mockResolvedValue({ total: 600, saldo: 600, aprobado: 0, anticipo_requerido: 0 });
  vi.spyOn(pagosApi, 'getIntentoActivo').mockResolvedValue(null);
  vi.spyOn(pagosApi, 'create').mockResolvedValue({ pago_id: 88, monto: 600, moneda: 'GTQ', estado: 'procesando' });
  vi.spyOn(reservasApi, 'getById').mockRejectedValue(new Error('unavailable details'));
});
afterEach(() => { vi.restoreAllMocks(); sessionStorage.clear(); });
it('bloquea un nuevo intento si el total del carrito y el resumen financiero difieren', async () => {
  renderWithProviders(<CheckoutPage />);
  await waitFor(() => expect(pagosApi.getIntentoActivo).toHaveBeenCalled());
  const button = screen.queryByRole('button', { name: 'Continuar al pago' });
  if (button) await userEvent.setup().click(button);
  expect(pagosApi.create).not.toHaveBeenCalled();
  expect(screen.getByRole('alert')).toHaveTextContent(/importe|total|coincid/i);
});
